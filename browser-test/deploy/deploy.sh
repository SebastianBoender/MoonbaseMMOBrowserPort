#!/usr/bin/env bash
# Run on your development computer. Only browser assets and Python host are uploaded.
set -Eeuo pipefail
ROOT=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
usage() { echo "Usage: $0 USER@VPS [--domain moonbasemmo.com] | --package-only [--domain DOMAIN]"; }
TARGET=""; DOMAIN=moonbasemmo.com; PACKAGE_ONLY=0
while (($#)); do
  case "$1" in
    --domain) DOMAIN=${2:?Missing domain}; shift 2 ;;
    --package-only) PACKAGE_ONLY=1; shift ;;
    --help|-h) usage; exit 0 ;;
    --*) usage >&2; exit 2 ;;
    *) [[ -z "$TARGET" ]] || { usage >&2; exit 2; }; TARGET=$1; shift ;;
  esac
done
[[ "$DOMAIN" =~ ^([a-z0-9]([a-z0-9-]*[a-z0-9])?\.)+[a-z]{2,63}$ ]] || { echo 'Invalid DNS domain.' >&2; exit 2; }
if (( !PACKAGE_ONLY )); then
  [[ "$TARGET" =~ ^[a-zA-Z0-9_][a-zA-Z0-9_.@:-]*$ ]] || { usage >&2; exit 2; }
  command -v ssh >/dev/null; command -v scp >/dev/null
fi
python3 "$ROOT/setup.py"
mkdir -p "$ROOT/deploy/dist"
STAGING=$(mktemp -d)
trap 'rm -rf -- "$STAGING"' EXIT
cp -a "$ROOT/public" "$STAGING/public"
python3 "$ROOT/deploy/version_assets.py" "$STAGING/public"
cp "$ROOT/serve.py" "$ROOT/mus_bridge.py" "$ROOT/deploy/install.sh" "$STAGING/"
printf '%s\n' "$DOMAIN" > "$STAGING/domain.txt"
# No original EXE, source scripts, local logs, caches or credentials in the package.
find "$STAGING" -type d -name __pycache__ -prune -exec rm -rf -- {} +
ARCHIVE="$ROOT/deploy/dist/moonbase-deploy.tar.gz"
tar -C "$STAGING" -czf "$ARCHIVE" public serve.py mus_bridge.py install.sh domain.txt
printf 'Deployment package: %s\n' "$ARCHIVE"
(( !PACKAGE_ONLY )) || exit 0
REMOTE_DIR=$(ssh -- "$TARGET" 'mktemp -d /tmp/moonbase-deploy.XXXXXXXX')
[[ "$REMOTE_DIR" =~ ^/tmp/moonbase-deploy\.[a-zA-Z0-9]+$ ]] || { echo 'Unexpected remote staging directory.' >&2; exit 1; }
scp -- "$ARCHIVE" "$TARGET:$REMOTE_DIR/release.tar.gz"
# The path is generated by mktemp and validated above; no arbitrary shell input.
ssh -t -- "$TARGET" "tar -xzf '$REMOTE_DIR/release.tar.gz' -C '$REMOTE_DIR' && if [ \"\$(id -u)\" = 0 ]; then bash '$REMOTE_DIR/install.sh'; else sudo bash '$REMOTE_DIR/install.sh'; fi"
echo "Deployed https://$DOMAIN. Staging files remain at $REMOTE_DIR for inspection."
